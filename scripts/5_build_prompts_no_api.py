# Question frames = distinct phrasing/structure, independent of topic.
# Designed to vary length and "angle" (how/what/compare/why/give-example).
FRAMES = [
    "What is {a}, and why does it matter in {topic}?",
    "How does {a} work?",
    "Explain {a} as if teaching a beginner.",
    "What's a common misconception about {a}?",
    "Compare {a} to a related concept within {topic}.",
    "Walk me through a real-world example involving {a}.",
    "Why is {a} considered important by experts in {topic_label}?",
    "What are the practical implications of {a}?",
    "How would you explain {a} to someone with no background in {topic_label}?",
]

# Human-readable topic labels for use inside frames.
TOPIC_LABELS = {
    "poetry": "poetry",
    "python_code": "Python programming",
    "medical_advice": "medicine",
    "cooking": "cooking",
    "legal": "law",
}

N_NEW_PER_TOPIC = 85


def build_new_prompts(topic: str) -> list[str]:
    """
    Each aspect is used EXACTLY ONCE, paired with exactly one frame
    (cycling through FRAMES in a fixed, deterministic rotation). This
    guarantees no two prompts ever share an aspect, which is what caused
    the high-similarity flags in the earlier itertools.product version
    (same aspect asked via multiple frames looks near-identical to a
    word-overlap similarity metric like TF-IDF).
    """
    aspects = SUB_ASPECTS[topic]
    label = TOPIC_LABELS[topic]

    assert len(aspects) >= N_NEW_PER_TOPIC, (
        f"{topic}: need >= {N_NEW_PER_TOPIC} aspects, have {len(aspects)}"
    )

    prompts = []
    for i, aspect in enumerate(aspects[:N_NEW_PER_TOPIC]):
        frame = FRAMES[i % len(FRAMES)]
        q = frame.format(a=aspect, topic=label, topic_label=label)
        q = q[0].upper() + q[1:]
        prompts.append(q)

    return prompts


def build_all(output_path: str = "data/prompts_candidate_100.json"):
    all_prompts = {}
    for topic, seeds in SEED_PROMPTS.items():
        new_prompts = build_new_prompts(topic)
        print(f"[Topic: {topic}] {len(seeds)} seed + {len(new_prompts)} new = {len(seeds) + len(new_prompts)} total")
        all_prompts[topic] = seeds + new_prompts

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w") as f:
        json.dump(all_prompts, f, indent=2)
    print(f"\nSaved to {output_path} — zero API calls used.")
    return all_prompts


if __name__ == "__main__":
    build_all()
