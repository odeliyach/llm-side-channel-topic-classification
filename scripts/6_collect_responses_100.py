"""
6_collect_responses_100.py
---------------------------
Collects streaming LLM responses for the 100-prompt-per-topic pool
generated by 5_build_prompts_no_api.py, saving the token-length sequences
to data/responses_100.json — same format as the original responses.json
so that 2_train_evaluate.py and 3_pairwise_heatmap.py work on it unchanged.

Run on YOUR machine with your Groq API key:
    python 6_collect_responses_100.py

It saves progress after every successful response, so if it crashes or
hits a rate limit mid-run, just re-run it — it will skip already-collected
responses and resume from where it left off.

Expected run time: ~45-90 min for all 500 responses at Groq free-tier
rate limits (1000 req/day, but streaming has throughput limits too).
"""

import json
import os
import time
from groq import Groq

API_KEY = "TOKEN" # ← paste your Groq API key here
MODEL = "meta-llama/llama-4-scout-17b-16e-instruct"
PROMPTS_PATH = "data/prompts_candidate_100.json"
OUTPUT_PATH = "data/responses_100.json"

SYSTEM_PROMPT = (
    "You are a helpful assistant. Answer the user's question clearly and "
    "informatively in 3-5 sentences."
)

client = Groq(api_key=API_KEY)


def collect_response(prompt: str) -> list[int]:
    """
    Stream one response and return the list of token lengths,
    exactly as 1_generate_data.py does it.
    """
    token_lengths = []
    stream = client.chat.completions.create(
        model=MODEL,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": prompt},
        ],
        stream=True,
    )
    for chunk in stream:
        delta = chunk.choices[0].delta
        if delta.content:
            token_lengths.append(len(delta.content))
    return token_lengths


def already_collected(existing: list[dict], topic: str, prompt_index: int) -> bool:
    return any(
        r["topic"] == topic and r["prompt_index"] == prompt_index
        for r in existing
    )


def main():
    # Load the 100-prompt pool.
    with open(PROMPTS_PATH) as f:
        all_prompts = json.load(f)

    # Load any already-collected results so we can resume.
    if os.path.exists(OUTPUT_PATH):
        with open(OUTPUT_PATH) as f:
            results = json.load(f)
        print(f"Resuming — {len(results)} responses already collected.")
    else:
        results = []

    total = sum(len(prompts) for prompts in all_prompts.values())
    done = len(results)

    for topic, prompts in all_prompts.items():
        for i, prompt in enumerate(prompts):
            if already_collected(results, topic, i):
                continue  # skip already done

            done += 1
            print(f"[{done}/{total}] topic={topic}, prompt_index={i}")

            try:
                token_lengths = collect_response(prompt)
                results.append({
                    "topic": topic,
                    "prompt_index": i,
                    "prompt": prompt,
                    "token_lengths": token_lengths,
                })
                # Save after every response — crash-safe.
                with open(OUTPUT_PATH, "w") as f:
                    json.dump(results, f, indent=2)

            except Exception as e:
                print(f"  ERROR: {e} — waiting 30s then retrying once.")
                time.sleep(30)
                try:
                    token_lengths = collect_response(prompt)
                    results.append({
                        "topic": topic,
                        "prompt_index": i,
                        "prompt": prompt,
                        "token_lengths": token_lengths,
                    })
                    with open(OUTPUT_PATH, "w") as f:
                        json.dump(results, f, indent=2)
                except Exception as e2:
                    print(f"  Retry also failed: {e2} — skipping and continuing.")

            # Polite delay to stay within rate limits.
            time.sleep(1.5)

    print(f"\nDone. {len(results)} responses saved to {OUTPUT_PATH}.")
    print("You can now run 2_train_evaluate.py and 3_pairwise_heatmap.py")
    print("on this file by changing DATA_PATH at the top of those scripts.")


if __name__ == "__main__":
    main()
